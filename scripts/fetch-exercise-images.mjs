/**
 * Downloads exercise imagery from the free-exercise-db dataset (public domain,
 * Unlicense) and writes downscaled WebP frames into public/ex/.
 *
 * The output is committed, so this only needs to run when the mapping changes:
 *   npm i -D sharp && node scripts/fetch-exercise-images.mjs
 *
 * Each dataset entry has two frames (start and end position). The app animates
 * between them, which reads like a GIF at a fraction of the size.
 */
import { mkdir, writeFile, readFile, rm } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "public", "ex");
const BASE = "https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises";
const DATASET = "https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json";
const WIDTH = 420;
const QUALITY = 72;

const { map } = JSON.parse(await readFile(join(ROOT, "scripts", "exercise-image-map.json"), "utf8"));

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });

const written = [];
let bytes = 0;

for (const [key, datasetId] of Object.entries(map)) {
  for (const frame of [0, 1]) {
    const url = `${BASE}/${encodeURIComponent(datasetId)}/${frame}.jpg`;
    const res = await fetch(url);
    if (!res.ok) {
      console.error(`MISS ${key} frame ${frame}: ${res.status} ${url}`);
      continue;
    }
    const buf = Buffer.from(await res.arrayBuffer());
    const webp = await sharp(buf)
      .resize({ width: WIDTH, withoutEnlargement: true })
      .webp({ quality: QUALITY })
      .toBuffer();
    const name = `${key}-${frame}.webp`;
    await writeFile(join(OUT, name), webp);
    written.push(`/ex/${name}`);
    bytes += webp.length;
  }
  process.stdout.write(".");
}

// Consumed by the service worker so every image is available offline.
written.sort();
await writeFile(join(ROOT, "public", "image-manifest.json"), JSON.stringify(written, null, 0));

// The dataset also carries step-by-step instructions. They are more verbose than
// the hand-written cues in lib/exercises.ts, so they live in the overlay as a
// secondary reference rather than replacing them.
const catalog = await (await fetch(`${DATASET}`)).json();
const byId = new Map(catalog.map((e) => [e.id, e]));
const steps = {};
for (const [key, datasetId] of Object.entries(map)) {
  const entry = byId.get(datasetId);
  const list = entry?.instructions?.filter((s) => s.trim().length > 0) ?? [];
  if (list.length > 0) steps[key] = list;
}
await writeFile(
  join(ROOT, "lib", "exercise-steps.ts"),
  `// GENERATED by scripts/fetch-exercise-images.mjs - do not edit by hand.\n` +
    `// Source: free-exercise-db (public domain, Unlicense).\n` +
    `export const EXERCISE_STEPS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(steps, null, 2)};\n`,
);
console.log(`\n${Object.keys(steps).length} exercises with step-by-step instructions`);

// Generated so the app knows which exercises have imagery without a runtime probe.
const keys = Object.keys(map).sort();
await writeFile(
  join(ROOT, "lib", "exercise-images.ts"),
  `// GENERATED by scripts/fetch-exercise-images.mjs - do not edit by hand.\n` +
    `// Imagery: free-exercise-db (public domain, Unlicense).\n` +
    `export const IMAGE_KEYS: ReadonlySet<string> = new Set([\n` +
    keys.map((k) => `  "${k}",`).join("\n") +
    `\n]);\n`,
);

console.log(
  `\n${written.length} frames, ${(bytes / 1024 / 1024).toFixed(2)} MB total, ` +
    `${Math.round(bytes / written.length / 1024)} KB average`,
);
