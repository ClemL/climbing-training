/**
 * Derives the directory grouping from the section comments in lib/exercises.ts,
 * so the grouping cannot drift from the file it describes.
 *
 *   node scripts/generate-exercise-groups.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Section comment text -> [label shown in the directory, short label for the
 * filter grid]. The short one has to fit a third of a phone screen.
 */
const LABELS = {
  "General warm-up / mobility": ["Warm-Up & Mobility", "Warm-Up"],
  "Fingers / forearms": ["Fingers & Forearms", "Fingers"],
  "Barbell / dumbbell push": ["Push", "Push"],
  Pull: ["Pull", "Pull"],
  "Legs / hinge": ["Legs & Hips", "Legs"],
  Core: ["Core", "Core"],
  Climbing: ["Climbing", "Climbing"],
  "Elastic bands": ["Bands", "Bands"],
  "Standing only: no floor, no chair, minimal space": ["Standing Only", "Standing"],
  "Soccer: speed, agility, plyometrics": ["Soccer: Speed & Agility", "Soccer Speed"],
  "Soccer: prevention and strength": ["Soccer: Prevention", "Soccer Prev."],
  "Soccer: ball work": ["Soccer: Ball Work", "Ball Work"],
  Golf: ["Golf", "Golf"],
  Knee: ["Knee", "Knee"],
};

const src = await readFile(join(ROOT, "lib", "exercises.ts"), "utf8");

const groups = [];
let current = null;
let inObject = false;

for (const line of src.split("\n")) {
  if (line.startsWith("export const EXERCISES")) inObject = true;
  if (!inObject) continue;
  if (line === "};") break;

  const section = line.match(/^\s*\/\* -+ (.+?) -+ \*\/$/);
  if (section) {
    const mapped = LABELS[section[1]];
    if (!mapped) throw new Error(`Unmapped section comment: "${section[1]}"`);
    current = { label: mapped[0], short: mapped[1], keys: [] };
    groups.push(current);
    continue;
  }

  const entry = line.match(/^  (?:"([a-z0-9-]+)"|([a-z0-9-]+)): \{$/);
  if (entry && current) current.keys.push(entry[1] ?? entry[2]);
}

const total = groups.reduce((n, g) => n + g.keys.length, 0);
const body = groups
  .map(
    (g) =>
      `  {\n    label: ${JSON.stringify(g.label)},\n    short: ${JSON.stringify(g.short)},\n    keys: [\n${g.keys.map((k) => `      ${JSON.stringify(k)},`).join("\n")}\n    ],\n  },`,
  )
  .join("\n");

await writeFile(
  join(ROOT, "lib", "exercise-groups.ts"),
  `// GENERATED by scripts/generate-exercise-groups.mjs - do not edit by hand.\n` +
    `// Derived from the section comments in lib/exercises.ts.\n\n` +
    `export type ExerciseGroup = { label: string; short: string; keys: readonly string[] };\n\n` +
    `export const EXERCISE_GROUPS: readonly ExerciseGroup[] = [\n${body}\n];\n`,
);

console.log(`${groups.length} groups, ${total} exercises`);
for (const g of groups) console.log(`  ${g.label.padEnd(26)} ${g.keys.length}`);
